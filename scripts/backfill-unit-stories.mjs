// Generates the SQL that fills member_unit_stories (migration 0049) from the existing per-person
// member_stories rows, using the tested rules in scripts/lib/member-unit-story.mjs.
//
//   node scripts/backfill-unit-stories.mjs --in units.json --out apply.sql [--refresh]
//
// units.json is the result of scripts/unit-stories-export.sql (the same file the preview reads);
// look at `node scripts/preview-unit-stories.mjs` first. It holds real names and story text, and so
// does the SQL this writes, so keep both OUTSIDE the repo (the repo is public).
//
// Order: apply migration 0049, run apply.sql in the TVC ERP SQL editor, then read the check at the
// end of it. Nothing reads member_unit_stories yet and member_stories is not touched, so rolling back
// is just:  delete from member_unit_stories;  Re-running is safe (on conflict do nothing).
//
// --refresh: before the cutover to unit stories (the member_settings switch `unit_stories`), edits keep being
// made to the per-person stories, so run the export again and this with --refresh to OVERWRITE the unit rows
// with them. Only while nothing writes member_unit_stories (before the switch is on): after it, the unit
// stories are the live ones and a refresh would throw their edits away.
import { readFileSync, writeFileSync } from 'node:fs';
import { buildUnitStory } from './lib/member-unit-story.mjs';

const args = process.argv.slice(2);
const arg = (flag) => (args.includes(flag) ? args[args.indexOf(flag) + 1] : null);
const input = arg('--in');
const dest = arg('--out');
const refresh = args.includes('--refresh');
if (!input || !dest) {
  console.error('Usage: node scripts/backfill-unit-stories.mjs --in units.json --out apply.sql');
  process.exit(2);
}
const units = JSON.parse(readFileSync(input, 'utf8'));

const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const json = (v) => `${q(JSON.stringify(v))}::jsonb`;
const ts = (v) => (v ? `${q(v)}::timestamptz` : 'null');
const id = (v) => {
  if (!UUID.test(v ?? '')) throw new Error(`Not a uuid: ${v}`);
  return q(v);
};

const warnings = [];
const values = [];
const counts = { approved: 0, in_review: 0, draft: 0 };
for (const u of units) {
  const { story, winners } = buildUnitStory(u.rows);
  const odd = u.rows.filter((r) => !['approved', 'in_review', 'draft'].includes(r.status));
  if (odd.length) warnings.push(`${u.farm_unit}: ${odd.length} row(s) with status "${odd[0].status}" (a sent-back edit and its note are not carried over)`);
  // The editor opens with the live text, as it did for a seeded person, when there is no draft of its own.
  const draft = story.draft ?? story.approved ?? {};
  const draftPublic = story.draft ? story.draftPublic : (story.approvedPublic ?? false);
  const updatedAt = u.rows.map((r) => r.updated_at).filter(Boolean).sort().pop() ?? null;
  counts[story.status] += 1;
  values.push(
    `  (${id(u.household_id)}, ${json(draft)}, ${draftPublic ? 'true' : 'false'}, 0, '{}'::jsonb, ${q(story.status)}, ` +
      `${story.submitted ? json(story.submitted) : 'null'}, ${story.submitted ? (story.submittedPublic ? 'true' : 'false') : 'null'}, ${ts(story.submittedAt)}, ${story.submitted ? id(winners.submitted) : 'null'}, ` +
      `${story.approved ? json(story.approved) : 'null'}, ${story.approved ? (story.approvedPublic ? 'true' : 'false') : 'null'}, ${ts(story.approvedAt)}, ${ts(updatedAt) === 'null' ? 'now()' : ts(updatedAt)})`,
  );
}

const sql = `-- Generated by scripts/backfill-unit-stories.mjs. Holds real story text: keep outside the repo.
-- Expects migration 0049 (member_unit_stories) to be applied. ${refresh ? 'REFRESH: overwrites the unit rows with the per-person stories; only while the unit_stories switch is off.' : 'Safe to re-run.'}
-- ${units.length} units: ${counts.approved} approved, ${counts.in_review} in review, ${counts.draft} draft only.
${values.length ? `
insert into member_unit_stories
  (household_id, draft, draft_public, draft_version, draft_changed, status, submitted, submitted_public, submitted_at, submitted_by, approved, approved_public, approved_at, updated_at)
values
${values.join(',\n')}
${refresh ? `on conflict (household_id) do update set
  draft = excluded.draft, draft_public = excluded.draft_public, draft_version = 0, draft_changed = '{}'::jsonb, status = excluded.status,
  submitted = excluded.submitted, submitted_public = excluded.submitted_public, submitted_at = excluded.submitted_at, submitted_by = excluded.submitted_by,
  approved = excluded.approved, approved_public = excluded.approved_public, approved_at = excluded.approved_at, updated_at = excluded.updated_at;` : 'on conflict (household_id) do nothing;'}
` : ''}
-- Check: expect ${units.length} units here, and the same split as above. To undo: delete from member_unit_stories;
select count(*) as units,
       count(*) filter (where status = 'approved') as approved,
       count(*) filter (where status = 'in_review') as in_review,
       count(*) filter (where status = 'draft') as draft_only,
       count(*) filter (where approved_public) as public_on_tvc_farm
from member_unit_stories;
`;
writeFileSync(dest, sql);
console.log(`Wrote ${dest}: ${units.length} units (${counts.approved} approved, ${counts.in_review} in review, ${counts.draft} draft only).`);
for (const w of warnings) console.log(`Warning: ${w}`);
